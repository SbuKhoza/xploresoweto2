"use strict"
const { test, beforeEach } = require("node:test")
const assert = require("node:assert/strict")
const { setup, req, rejects, makeOrg, addMember, makeSuperAdmin } = require("./helpers")
const L = require("../src/handlers/listings")

let env
beforeEach(() => {
  env = setup()
  makeOrg(env, "orgA", { type: "restaurant" }); makeOrg(env, "orgB", { type: "restaurant" }); makeOrg(env, "orgT", { type: "tour_guide" })
  addMember(env, "orgA", "contentA", "content_manager"); addMember(env, "orgA", "empA", "employee"); addMember(env, "orgB", "ownerB", "owner"); addMember(env, "orgT", "guide", "owner")
  env.addUser("ed", { customClaims: { editor: true } }); env.seed("platform-editors/ed", { uid: "ed", role: "editor", active: true })
  env.addUser("plain")
})
const sub = (uid, data = {}, o) => L.submitListing(req(uid, { requestId: "req-00000001", organisationId: "orgA", kind: "new", payload: { name: "Mama Kitchen", description: "Food", phone: "0110000000" }, imagePaths: [], ...data }, o))
const editor = (data) => req("ed", data, { claims: { editor: true } })

test("submitListing: members with content.manage only; other organisations, employees, unverified users refused", async () => {
  await rejects(sub("empA"), "permission-denied"); await rejects(sub("ownerB"), "permission-denied"); await rejects(sub("plain"), "permission-denied")
  await rejects(sub("contentA", {}, { verified: false }), "failed-precondition", "email-not-verified")
  assert.equal(env.list("listing-submissions").length, 0)
  const r = await sub("contentA"); assert.deepEqual([r.submissionId, r.status, r.duplicate], ["orgA_req-00000001", "pending", false])
  assert.equal((await sub("contentA")).duplicate, true); assert.equal(env.list("listing-submissions").length, 1)
})
test("submitListing: payload allow-list, image path scoping, unsupported provider types", async () => {
  await rejects(sub("contentA", { payload: { name: "X", isActive: true } }), "invalid-argument")
  await rejects(sub("contentA", { payload: { name: "X", organisationId: "orgB" } }), "invalid-argument")
  await rejects(sub("contentA", { payload: { description: "no name" } }), "invalid-argument")
  await rejects(sub("contentA", { imagePaths: ["listing-submissions/orgB/orgB_req-00000001/a.jpg"] }), "invalid-argument")
  await rejects(sub("contentA", { imagePaths: ["listing-submissions/orgA/orgA_req-00000001/../x.jpg"] }), "invalid-argument")
  await rejects(L.submitListing(req("guide", { requestId: "req-00000001", organisationId: "orgT", kind: "new", payload: { name: "Tour" } })), "failed-precondition", "listing-type-not-supported-yet")
})
test("reviewListingSubmission: only active staff; approval publishes isActive+organisationId, copies images, idempotent", async () => {
  env.bucket.put("listing-submissions/orgA/orgA_req-00000001/front.jpg")
  await sub("contentA", { imagePaths: ["listing-submissions/orgA/orgA_req-00000001/front.jpg"] })
  await rejects(L.reviewListingSubmission(req("contentA", { submissionId: "orgA_req-00000001", decision: "approve" })), "permission-denied")
  await rejects(L.reviewListingSubmission(req("plain", { submissionId: "orgA_req-00000001", decision: "approve" }, { claims: { editor: true } })), "permission-denied") // claim without record
  const r = await L.reviewListingSubmission(editor({ submissionId: "orgA_req-00000001", decision: "approve" }))
  assert.deepEqual([r.status, r.duplicate], ["approved", false])
  const pub = env.get("restaurants/orgA_req-00000001")
  assert.deepEqual([pub.name, pub.isActive, pub.organisationId, pub.publishedBy], ["Mama Kitchen", true, "orgA", "ed"])
  assert.equal(pub.images.length, 1); assert.match(pub.images[0], /^https:\/\/firebasestorage\.googleapis\.com\/v0\/b\/xploresoweto\.firebasestorage\.app\/o\/restaurants%2ForgA%2F/)
  assert.equal(env.bucket.copies.length, 1)
  assert.equal((await L.reviewListingSubmission(editor({ submissionId: "orgA_req-00000001", decision: "approve" }))).duplicate, true)
  assert.equal(env.list("restaurants").length, 1)
  assert.equal(env.list("audit-log").filter((a) => a.action === "listing.publish").length, 1)
})
test("reviewListingSubmission: reject; a suspended organisation cannot publish; change requests cannot touch another organisation's listing", async () => {
  await sub("contentA"); const sa = makeSuperAdmin(env, "root")
  assert.equal((await L.reviewListingSubmission(sa({ submissionId: "orgA_req-00000001", decision: "reject", note: "needs photos" }))).status, "rejected")
  assert.equal(env.list("restaurants").length, 0)
  await sub("contentA", { requestId: "req-00000002" })
  env.db._write({ type: "update", path: "organisations/orgA", data: { approvalStatus: "suspended", active: false } })
  await rejects(L.reviewListingSubmission(sa({ submissionId: "orgA_req-00000002", decision: "approve" })), "failed-precondition", "organisation-inactive")
  env.db._write({ type: "update", path: "organisations/orgA", data: { approvalStatus: "approved", active: true } })
  env.seed("restaurants/foreign", { name: "Not theirs", organisationId: "orgB", isActive: true })
  await L.submitListing(req("contentA", { requestId: "req-00000003", organisationId: "orgA", kind: "change", targetDocId: "foreign", payload: { description: "hijack" } }))
  await rejects(L.reviewListingSubmission(sa({ submissionId: "orgA_req-00000003", decision: "approve" })), "failed-precondition", "target-not-owned-by-organisation")
  assert.notEqual(env.get("restaurants/foreign").description, "hijack")
})
